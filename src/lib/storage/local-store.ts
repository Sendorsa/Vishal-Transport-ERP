export interface StorageMeta {
  version: number
  seededAt: string
  /** DEMO / EMPTY = generated by the app; RESTORED = loaded from a backup or import file (real data — never re-seeded). */
  source?: "DEMO" | "EMPTY" | "RESTORED"
}

interface Encoded {
  cols: string[]
  rows: unknown[][]
}

const browserCache = new Map<string, unknown>()

/**
 * Where data lives for this call. Browser: localStorage (+ an in-memory parse cache). Server (Supabase backend): the
 * request scope — collections loaded from the database for this request; writes are only recorded in memory and turned
 * into SQL by the unit of work (src/lib/server/erp) inside one database transaction.
 */
const cacheOf = () => requestScope()?.cache ?? browserCache

export function isBrowser() {
  return !!requestScope() || (typeof window !== "undefined" && typeof window.localStorage !== "undefined")
}

/** localStorage, or the request scope's write recorder on the server (nothing is serialised there). */
function ls(): Pick<Storage, "getItem" | "setItem" | "removeItem"> {
  const scope = requestScope()
  if (!scope) return window.localStorage
  return { getItem: () => null, setItem: (k) => void scope.written.add(k), removeItem: (k) => void scope.written.add(k) }
}

function encode<T extends object>(items: T[]): Encoded {
  const cols: string[] = []
  const seen = new Set<string>()
  for (const item of items)
    for (const k of Object.keys(item))
      if (!seen.has(k)) {
        seen.add(k)
        cols.push(k)
      }
  return { cols, rows: items.map((it) => cols.map((c) => (it as Record<string, unknown>)[c] ?? null)) }
}

function decode<T>(enc: Encoded): T[] {
  return enc.rows.map((row) => {
    const o: Record<string, unknown> = {}
    enc.cols.forEach((c, i) => (o[c] = row[i]))
    return o as T
  })
}

export class StorageQuotaError extends Error {
  constructor() {
    super("Browser storage is full. Reset demo data from Settings to free space.")
  }
}

/* ------------------------------------------------------------------ Transactions */

/** Original raw value of every key written during the open transaction (null = key didn't exist). */
let txOriginals: Map<string, string | null> | null = null

function remember(key: string) {
  if (txOriginals && !txOriginals.has(key)) txOriginals.set(key, ls().getItem(key))
}

/**
 * Runs `fn` so that all its localStorage writes land together or not at all: if it throws (a
 * validation error, storage full, a failed audit write), every key it touched is restored.
 * Used by the API so a record change and its audit event can't be separated.
 * Callers must not overlap transactions — the API serialises them (see `tx` in lib/api/index.ts).
 */
export async function runInTransaction<T>(fn: () => Promise<T>): Promise<T> {
  // Server: the database transaction around the whole request rolls everything back on error.
  if (!isBrowser() || requestScope()) return fn()
  if (txOriginals) throw new Error("Nested storage transaction")
  txOriginals = new Map()
  const originals = txOriginals
  try {
    const result = await fn()
    txOriginals = null
    return result
  } catch (e) {
    txOriginals = null
    browserCache.clear()
    // Restore every key on its own: one failed restore must not stop the others.
    for (const [key, raw] of originals) {
      try {
        if (raw === null) window.localStorage.removeItem(key)
        else window.localStorage.setItem(key, raw)
      } catch (restoreError) {
        console.error(`Could not restore ${key} after a failed change`, restoreError)
      }
    }
    throw e
  }
}

function setItem(key: string, value: string) {
  remember(key)
  try {
    ls().setItem(key, value)
  } catch (e) {
    if (e instanceof DOMException && (e.name === "QuotaExceededError" || e.code === 22)) throw new StorageQuotaError()
    throw e
  }
}

function removeItem(key: string) {
  remember(key)
  ls().removeItem(key)
}

/* ------------------------------------------------------------------ Audit events (append-only) */

export const AUDIT_KEY = `${STORAGE_PREFIX}auditEvents`

/** All audit events, oldest first. */
export function readAuditEvents(): AuditEvent[] {
  if (!isBrowser()) return []
  if (cacheOf().has(AUDIT_KEY)) return cacheOf().get(AUDIT_KEY) as AuditEvent[]
  if (requestScope()) throw new NeedData(AUDIT_KEY)
  const raw = ls().getItem(AUDIT_KEY)
  const items = raw ? decode<AuditEvent>(JSON.parse(raw) as Encoded) : []
  cacheOf().set(AUDIT_KEY, items)
  return items
}

export const AUDIT_REVIEWS_KEY = `${STORAGE_PREFIX}auditReviews`
/** Keys that survive data resets: the audit trail and the Owner's reviews of it. */
const KEPT_KEYS = new Set([AUDIT_KEY, AUDIT_REVIEWS_KEY])

/** The Owner's reviews of deletion events, oldest first. */
export function readAuditReviews(): AuditReview[] {
  if (!isBrowser()) return []
  if (cacheOf().has(AUDIT_REVIEWS_KEY)) return cacheOf().get(AUDIT_REVIEWS_KEY) as AuditReview[]
  if (requestScope()) throw new NeedData(AUDIT_REVIEWS_KEY)
  const raw = ls().getItem(AUDIT_REVIEWS_KEY)
  const items = raw ? (JSON.parse(raw) as AuditReview[]) : []
  cacheOf().set(AUDIT_REVIEWS_KEY, items)
  return items
}

/** Append-only, like the events themselves. */
export function appendAuditReviews(reviews: AuditReview[]) {
  const scope = requestScope()
  if (scope) {
    // Server: the request's new reviews (inserted in its transaction); the loaded list, if any, sees them too.
    scope.newReviews.push(...reviews)
    if (scope.cache.has(AUDIT_REVIEWS_KEY)) scope.cache.set(AUDIT_REVIEWS_KEY, [...(scope.cache.get(AUDIT_REVIEWS_KEY) as AuditReview[]), ...reviews])
    return
  }
  const next = [...readAuditReviews(), ...reviews]
  setItem(AUDIT_REVIEWS_KEY, JSON.stringify(next))
  cacheOf().set(AUDIT_REVIEWS_KEY, next)
}

/** The only write path for audit events: append. There is no update or delete. */
export function appendAuditEvent(event: AuditEvent) {
  const scope = requestScope()
  if (scope) {
    // Server: never needs the whole trail to append (it isn't loaded for ordinary writes).
    scope.newEvents.push(event)
    if (scope.cache.has(AUDIT_KEY)) scope.cache.set(AUDIT_KEY, [...(scope.cache.get(AUDIT_KEY) as AuditEvent[]), event])
    return
  }
  const next = [...readAuditEvents(), event]
  setItem(AUDIT_KEY, JSON.stringify(encode(next)))
  cacheOf().set(AUDIT_KEY, next)
}

export function readCollection<K extends CollectionKey>(key: K): CollectionMap[K][] {
  if (!isBrowser()) return []
  const full = STORAGE_PREFIX + STORAGE_NAME[key]
  if (cacheOf().has(full)) return cacheOf().get(full) as CollectionMap[K][]
  if (requestScope()) throw new NeedData(full)
  const raw = ls().getItem(full)
  const items = raw ? decode<CollectionMap[K]>(JSON.parse(raw) as Encoded) : []
  cacheOf().set(full, items)
  return items
}

export function writeCollection<K extends CollectionKey>(key: K, items: CollectionMap[K][]) {
  const full = STORAGE_PREFIX + STORAGE_NAME[key]
  if (requestScope() && !cacheOf().has(full)) throw new NeedData(full) // never write a collection without its original
  setItem(full, requestScope() ? "" : JSON.stringify(encode(items)))
  cacheOf().set(full, items)
}

/** Settings as one object; vehicle types and petrol pumps are stored in their own keys. */
export function readSettings(): Settings | null {
  if (!isBrowser()) return null
  if (cacheOf().has(SETTINGS_KEY)) return cacheOf().get(SETTINGS_KEY) as Settings
  if (requestScope()) throw new NeedData(SETTINGS_KEY)
  const raw = window.localStorage.getItem(SETTINGS_KEY)
  if (!raw) return null
  const ls = window.localStorage
  const s = JSON.parse(raw) as Settings
  s.vehicleTypes = JSON.parse(ls.getItem(VEHICLE_TYPES_KEY) ?? "null") ?? s.vehicleTypes ?? []
  delete (s as Partial<Record<"dieselVendors", unknown>>).dieselVendors // lives in vt:fuelStations now
  cacheOf().set(SETTINGS_KEY, s)
  return s
}

export function writeSettings(settings: Settings) {
  if (requestScope()) {
    if (!cacheOf().has(SETTINGS_KEY)) throw new NeedData(SETTINGS_KEY)
    setItem(SETTINGS_KEY, "")
    cacheOf().set(SETTINGS_KEY, settings)
    return
  }
  const { vehicleTypes, ...rest } = settings
  setItem(VEHICLE_TYPES_KEY, JSON.stringify(vehicleTypes))
  setItem(SETTINGS_KEY, JSON.stringify(rest))
  cacheOf().set(SETTINGS_KEY, settings)
}

/**
 * One-time, non-destructive move to the current key layout:
 * vt:diesel_entries → vt:fuelEntries, master lists out of vt:settings,
 * fuel type dropped from fuel entries (it lives on the vehicle), and a `status` on every
 * master record (missing → ACTIVE; petrol pumps' old `active` flag → ACTIVE / INACTIVE), and a
 * dated `statusHistory` on customers and vehicles (inferred by `historyOf`: ACTIVE from creation,
 * a non-active status from the last update), so past months never take today's status; and
 * `vehicleAssignments` for vehicles without any (inferred from their entries, so every entry
 * stays under the customer it was reported under).
 */
let migrated = false

/** `force`: run again after data was replaced in this session (a restored backup may be an older shape). */
export function migrateStorage(force = false) {
  // Never on the shared database: its schema migrations are SQL (supabase/migrations), never browser code.
  if (!isBrowser() || requestScope() || (migrated && !force)) return
  migrated = true
  const ls = window.localStorage
  const legacy = `${STORAGE_PREFIX}diesel_entries`
  if (ls.getItem(legacy) && !ls.getItem(`${STORAGE_PREFIX}fuelEntries`)) {
    ls.setItem(`${STORAGE_PREFIX}fuelEntries`, ls.getItem(legacy)!)
    ls.removeItem(legacy)
  }
  const raw = ls.getItem(SETTINGS_KEY)
  // Fuel stations → their own collection (vt:fuelStations), same ids so every entry still points at its station.
  const stationsKey = STORAGE_PREFIX + STORAGE_NAME.fuel_stations
  if (ls.getItem(stationsKey) === null) {
    const legacy = (JSON.parse(ls.getItem(LEGACY_PUMPS_KEY) ?? "null") ?? (raw ? JSON.parse(raw).dieselVendors : null)) as (Record<string, unknown> & { active?: boolean; status?: string })[] | null
    if (legacy) {
      const now = new Date().toISOString()
      writeCollection(
        "fuel_stations",
        legacy.map(({ active, ...p }) => ({ createdAt: now, updatedAt: now, ...p, status: p.status ?? (active === false ? "INACTIVE" : "ACTIVE") })) as never
      )
      ls.removeItem(LEGACY_PUMPS_KEY)
    }
  }
  if (raw && (ls.getItem(VEHICLE_TYPES_KEY) === null || "vehicleTypes" in JSON.parse(raw) || "dieselVendors" in JSON.parse(raw))) {
    cacheOf().delete(SETTINGS_KEY)
    const s = readSettings()
    if (s) writeSettings(s)
  }
  for (const name of ["customers", "vehicles", "drivers"] as const) {
    const list = readCollection(name) as { status?: string }[]
    if (list.some((e) => !e.status)) writeCollection(name, list.map((e) => (e.status ? e : { ...e, status: "ACTIVE" })) as never)
  }
  const customers = readCollection("customers")
  if (customers.some((e) => !e.statusHistory)) writeCollection("customers", customers.map((e) => (e.statusHistory ? e : { ...e, statusHistory: historyOf(e) })))
  const vehicles = readCollection("vehicles")
  if (vehicles.some((e) => !e.statusHistory)) writeCollection("vehicles", vehicles.map((e) => (e.statusHistory ? e : { ...e, statusHistory: historyOf(e) })))
  const assigned = readCollection("vehicle_assignments")
  const has = new Set(assigned.map((a) => a.vehicleId))
  const todo = vehicles.filter((v) => !has.has(v.id))
  if (todo.length) {
    const entries = [...readCollection("diesel_entries"), ...readCollection("adblue_entries")]
    const now = new Date().toISOString()
    const added = todo.flatMap((v) => inferAssignments(v, entries, todayISO()).map((p, i) => ({ ...p, id: `vas_${v.id}_${i}`, createdAt: now, updatedAt: now })))
    if (added.length) writeCollection("vehicle_assignments", [...assigned, ...added])
  }
  // The company's Diesel Tanker as a selectable fuel source (cargo inventory, not a pump we owe).
  const stationList = readCollection("fuel_stations")
  if (stationList.length && !stationList.some((v) => v.id === "dv_tanker")) {
    const now = new Date().toISOString()
    writeCollection("fuel_stations", [...stationList, { id: "dv_tanker", name: "Diesel Tanker", location: "Company tanker", isInterCompany: false, creditDays: 0, status: "ACTIVE", isTanker: true, createdAt: now, updatedAt: now }])
  }
  // AdBlue → inventory: each legacy entry bought at a station becomes a purchase of the same litres
  // and ₹ (so its value in every report is unchanged) plus the draw; it leaves the station ledger.
  const adEntries = readCollection("adblue_entries")
  const legacyAd = adEntries.filter((e) => e.vendorId)
  if (legacyAd.length) {
    const stations = new Map(readCollection("fuel_stations").map((v) => [v.id, v.name]))
    const reg = new Map(readCollection("vehicles").map((v) => [v.id, v.regNo]))
    const now = new Date().toISOString()
    writeCollection("adblue_purchases", [
      ...readCollection("adblue_purchases"),
      ...legacyAd.map((e) => ({
        id: `adp_${e.id}`,
        createdAt: e.createdAt ?? now,
        updatedAt: now,
        date: e.date,
        vendorName: stations.get(e.vendorId) ?? "Unknown vendor",
        product: "AdBlue",
        buckets: 1,
        litresPerBucket: e.quantityLitres,
        totalLitres: e.quantityLitres,
        pricePerBucket: e.amount,
        totalCost: e.amount,
        invoiceNo: e.invoiceNo,
        notes: `Migrated from the AdBlue entry for ${reg.get(e.vehicleId) ?? "a vehicle"} on ${e.date}`,
      })),
    ])
    writeCollection("adblue_entries", adEntries.map((e) => (e.vendorId ? { ...e, vendorId: "" } : e)))
  }
  // Tankers (answer 24): the single built-in tanker becomes the first tanker record, and every tanker load,
  // dispense and tanker fill saved before tankers existed is stamped with it — same litres, same history.
  const unstamped = [...readCollection("tanker_loads"), ...readCollection("tanker_dispenses"), ...readCollection("diesel_entries").filter(isTankerFill)].some((r) => !r.tankerId)
  const tankers = readCollection("tankers")
  if (unstamped && !tankers.some((t) => t.id === DEFAULT_TANKER_ID)) {
    const now = new Date().toISOString()
    const cfg = (raw ? (JSON.parse(raw) as { tanker?: { vehicleId: string | null; capacityLitres: number } }).tanker : undefined) ?? null
    const vehicle = cfg?.vehicleId ? readCollection("vehicles").find((v) => v.id === cfg.vehicleId) : undefined
    writeCollection("tankers", [
      ...tankers,
      {
        id: DEFAULT_TANKER_ID,
        name: vehicle ? `Diesel Tanker ${vehicle.regNo}` : "Diesel Tanker",
        regNo: vehicle?.regNo ?? "",
        vehicleId: vehicle?.id ?? null,
        capacityLitres: cfg?.capacityLitres ?? null,
        status: "ACTIVE",
        notes: "The company tanker before several tankers were tracked; earlier tanker records belong to it.",
        createdAt: now,
        updatedAt: now,
      },
    ])
  }
  const stamp = <K extends "tanker_loads" | "tanker_dispenses" | "diesel_entries">(key: K, applies: (r: CollectionMap[K]) => boolean) => {
    const list = readCollection(key) as (CollectionMap[K] & { tankerId?: string })[]
    if (list.some((r) => applies(r) && !r.tankerId)) writeCollection(key, list.map((r) => (applies(r) && !r.tankerId ? { ...r, tankerId: DEFAULT_TANKER_ID } : r)) as never)
  }
  stamp("tanker_loads", () => true)
  stamp("tanker_dispenses", () => true)
  stamp("diesel_entries", isTankerFill)
  ensureConfirmedTankers()
  const fills = readCollection("diesel_entries")
  if (fills.some((e) => "fuelType" in e))
    writeCollection(
      "diesel_entries",
      fills.map((e) => {
        const copy: Record<string, unknown> = { ...e }
        delete copy.fuelType
        return copy as unknown as typeof e
      })
    )
}

/**
 * The three confirmed tankers (CONFIRMED_TANKERS) in data that holds their vehicles: each tanker record is added
 * once if missing (same id as the fuel import) and linked to the one vehicle with its registration. Only fills in
 * what is missing — never renames, never moves history: records stay on the tanker or stock pool they name
 * (S-21, S-22). Recorded as SYSTEM events. Data without these vehicles (demo data, an empty workspace) is untouched.
 */
function ensureConfirmedTankers() {
  const vehicles = readCollection("vehicles")
  const tankers = readCollection("tankers")
  const now = new Date().toISOString()
  const events: AuditEvent[] = []
  const next = [...tankers]
  for (const c of CONFIRMED_TANKERS) {
    const matches = vehicles.filter((v) => normReg(v.regNo) === c.regNo)
    const vehicle = matches.length === 1 && !tankers.some((t) => t.vehicleId === matches[0].id) ? matches[0] : null
    const i = next.findIndex((t) => t.id === c.id || normReg(t.regNo) === c.regNo)
    const label = `${c.name} (${c.regNo})`
    if (i < 0) {
      if (!matches.length) continue
      const after: Tanker = { id: c.id, name: next.some((t) => t.name.trim().toLowerCase() === c.name.toLowerCase()) ? label : c.name, regNo: c.regNo, vehicleId: vehicle?.id ?? null, capacityLitres: null, status: "ACTIVE", notes: `${c.name} — registration ${c.regNo} (owner, 15 Oct 2026). Added by the app from the confirmed tanker list; earlier tanker records stay where they were recorded until the stock is split.`, createdAt: now, updatedAt: now }
      next.push(after)
      events.push(systemEvent({ action: "CREATED", module: "Diesel Tanker", recordType: "Tanker", recordId: c.id, label, after, note: "Confirmed tanker added by the app (answer 24, owner 15 Oct 2026)" }, now))
    } else if (!next[i].vehicleId && vehicle) {
      const before = next[i]
      next[i] = { ...before, vehicleId: vehicle.id, updatedAt: now }
      events.push(systemEvent({ action: "UPDATED", module: "Diesel Tanker", recordType: "Tanker", recordId: before.id, label, before, after: next[i], note: `Linked to its vehicle record ${vehicle.regNo} (same registration)` }, now))
    }
  }
  if (!events.length) return
  writeCollection("tankers", next)
  for (const e of events) appendAuditEvent(e)
}

const systemEvent = (input: Parameters<typeof buildEvent>[0], at: string) =>
  buildEvent(input, { kind: "SYSTEM", userId: null, name: null, role: null }, `aud_${crypto.randomUUID().replace(/-/g, "").slice(0, 12)}`, at)

export function readMeta(): StorageMeta | null {
  if (!isBrowser() || requestScope()) return null
  const raw = window.localStorage.getItem(META_KEY)
  return raw ? (JSON.parse(raw) as StorageMeta) : null
}

export function writeMeta(meta: StorageMeta) {
  setItem(META_KEY, JSON.stringify(meta))
}

/**
 * Kept by data resets: the audit log and its reviews, and the session (vt:ui:* — role, company,
 * month). Wiping the role made it fall back to Owner, so a reset could promote the person doing it.
 */
const keptByReset = (k: string) => KEPT_KEYS.has(k) || k.startsWith(`${STORAGE_PREFIX}ui:`)

/** Removes every data key this app owns — never the audit trail or the session. */
export function clearAll() {
  if (requestScope()) throw new Error("The shared database is never cleared or reset from the application.")
  if (!isBrowser()) return
  Object.keys(window.localStorage)
    .filter((k) => k.startsWith(STORAGE_PREFIX) && !keptByReset(k))
    .forEach(removeItem)
  for (const k of [...browserCache.keys()]) if (!keptByReset(k)) browserCache.delete(k)
}

/** Approximate bytes used by this app (UTF-16 → 2 bytes per char). */
export function storageUsage() {
  if (!isBrowser() || requestScope()) return 0
  return Object.keys(window.localStorage)
    .filter((k) => k.startsWith(STORAGE_PREFIX))
    .reduce((s, k) => s + (window.localStorage.getItem(k)?.length ?? 0) * 2, 0)
}

/** Fires when another tab changes our data. Returns the collection name (or "settings"). */
export function subscribeExternal(cb: (name: string) => void) {
  if (!isBrowser()) return () => {}
  const handler = (e: StorageEvent) => {
    if (!e.key || !e.key.startsWith(STORAGE_PREFIX)) return
    cacheOf().delete(e.key)
    const name = e.key.slice(STORAGE_PREFIX.length)
    if (name === "vehicleTypes") {
      cacheOf().delete(SETTINGS_KEY)
      return cb("settings")
    }
    cb((Object.keys(STORAGE_NAME) as CollectionKey[]).find((k) => STORAGE_NAME[k] === name) ?? name)
  }
  window.addEventListener("storage", handler)
  return () => window.removeEventListener("storage", handler)
}
